interface DocCard {
  heading: string;
  blocks: string[];
}

interface ParteSection {
  id: string;
  title: string;
  introBlocks: string[];
  cards: DocCard[];
}

function parseCitationsDocument(raw: string): {
  headerTitle: string;
  headerSubtitle: string;
  headerDescription: string;
  partes: ParteSection[];
} {
  const parts = raw.split(/\n(?=# (?:PARTE |CONCLUSÃO ))/);
  const headerRaw = parts[0].replace(/\n---\s*$/, '').trim();
  const headerLines = headerRaw.split(/\n+/).map(l => l.trim()).filter(Boolean);

  const headerTitle = (headerLines[0] || '').replace(/^#\s+/, '').trim();
  const headerSubtitle = (headerLines[1] || '').replace(/^##\s+/, '').trim();
  const headerDescription = (headerLines[2] || '').replace(/^###\s+/, '').trim();

  const partes: ParteSection[] = parts.slice(1).map((partRaw, idx) => {
    const cleaned = partRaw.replace(/\n---\s*$/, '').trim();
    const lines = cleaned.split('\n');
    const title = lines[0].replace(/^#\s+/, '').trim();
    const rest = lines.slice(1).join('\n').trim();

    const subSections = rest.split(/\n(?=## )/);
    const introBlocks: string[] = [];
    const cards: DocCard[] = [];

    subSections.forEach((sec) => {
      const sTrim = sec.trim();
      if (!sTrim) return;
      if (sTrim.startsWith('## ')) {
        const sLines = sTrim.split('\n');
        const heading = sLines[0].replace(/^##\s+/, '').trim();
        const body = sLines.slice(1).join('\n').replace(/\n---\s*$/, '').trim();
        const blocks = body ? body.split(/\n\n+/).map(b => b.trim()).filter(Boolean) : [];
        cards.push({ heading, blocks });
      } else {
        const blocks = sTrim.replace(/\n---\s*$/, '').trim().split(/\n\n+/).map(b => b.trim()).filter(Boolean);
        introBlocks.push(...blocks);
      }
    });

    return {
      id: `cit-parte-${idx + 1}`,
      title,
      introBlocks,
      cards
    };
  });

  return { headerTitle, headerSubtitle, headerDescription, partes };
}

const escapeHtml = (str: string) =>
  str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

const formatInline = (text: string) =>
  escapeHtml(text)
    .replace(/\*\*(.+?)\*\*/g, '<strong class="text-stone-100 font-bold">$1</strong>')
    .replace(/\*([^*]+?)\*/g, '<em class="italic text-amber-200/90">$1</em>');

